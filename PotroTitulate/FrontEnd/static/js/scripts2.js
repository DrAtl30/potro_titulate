function handleFileChange(requisito) {
    const fileInput = document.getElementById(`file-${requisito}`);
    const file = fileInput.files[0];

    if (file) {
        // Solo permitir archivos PDF
        const allowedExtensions = ['pdf'];
        const fileExtension = file.name.split('.').pop().toLowerCase();

        if (!allowedExtensions.includes(fileExtension)) {
            mostrarModal('Formato no permitido. Solo se aceptan archivos PDF.', 'errorModal');
            fileInput.value = '';
            return;
        }

        // Verificar longitud del nombre del archivo (incluyendo extensión)
        if (file.name.length > 50) {
            mostrarModal('El nombre del archivo no debe superar los 50 caracteres.', 'errorModal');
            fileInput.value = '';
            return;
        }

        const maxSizeMB = 3;
        const maxSizeBytes = maxSizeMB * 1024 * 1024;

        if (file.size > maxSizeBytes) {
            mostrarModal(`El archivo es demasiado grande. El tamaño máximo permitido es 3MB.`, 'errorModal');
            fileInput.value = '';
            return;
        }

        const confirmacion = confirm(`¿Estás seguro de que deseas subir el archivo "${file.name}"?`);
        if (!confirmacion) {
            return;
        }

        const formData = new FormData();
        formData.append('file', file);
        formData.append('requisito', requisito);
        formData.append('csrfmiddlewaretoken', document.querySelector('input[name="csrfmiddlewaretoken"]').value);

        fetch('/uploadDocument/', {
            method: 'POST',
            body: formData
        })
        .then(response => response.json())
        .then(data => {
            if (data.success) {
                mostrarModal(`Archivo "${file.name}" subido correctamente para ${requisito}`, 'successModal');
                updateEstado(requisito, 'pendiente');
                document.querySelector(`button[onclick="uploadFile('${requisito}')"]`).disabled = true;
            } else {
                mostrarModal(`Error al subir el archivo: ${data.error}`, 'errorModal');
            }
        })
        .catch(error => {
            console.error('Error:', error);
            mostrarAlerta('❌ Error al subir el archivo.', 'danger');
        });
    }
}

function cerrarSesion() {
    var form = document.createElement('form');
    form.method = 'POST';
    form.action = '/logout/';

    var csrfTokenElement = document.querySelector('input[name="csrfmiddlewaretoken"]');
    if (csrfTokenElement) {
        var csrfInput = document.createElement('input');
        csrfInput.type = 'hidden';
        csrfInput.name = 'csrfmiddlewaretoken';
        csrfInput.value = csrfTokenElement.value;
        form.appendChild(csrfInput);
    }

    sessionStorage.clear();
    localStorage.clear();

    document.body.appendChild(form);
    form.submit();

    setTimeout(() => {
        window.location.href = '/index/';
    }, 500);
}

function mostrarModal(mensaje, modalId) {
    var modal = document.getElementById(modalId);
    if (!modal) {
        console.error(`No se encontró el modal con ID ${modalId}`);
        return;
    }

    var modalMessage = modal.querySelector('.modalMessage');
    if (modalMessage) {
        modalMessage.textContent = mensaje;
    } else {
        console.warn(`No se encontró el elemento con clase 'modalMessage' dentro de ${modalId}`);
    }

    modal.style.display = 'flex';

    var closeBtn = modal.querySelector('.close');
    if (closeBtn) {
        closeBtn.onclick = function() {
            modal.style.display = 'none';
        };
    } else {
        console.warn(`No se encontró el botón de cierre en ${modalId}`);
    }

    window.onclick = function(event) {
        if (event.target == modal) {
            modal.style.display = 'none';
        }
    };

    window.onkeydown = function(event) {
        if (event.key === 'Escape') {
            modal.style.display = 'none';
        }
    };
}

function esperarCierreModal(modalId) {
    return new Promise((resolve) => {
        const modal = document.getElementById(modalId);
        const closeBtn = modal.querySelector('.close');

        closeBtn.onclick = () => {
            modal.style.display = 'none';
            resolve();
        };

        window.onclick = (event) => {
            if (event.target === modal) {
                modal.style.display = 'none';
                resolve();
            }
        };

        window.onkeydown = (event) => {
            const escapeKeys = ['Escape', 'Esc'];
            const escapeKeyCodes = [27];
            const escapeKeyCodesDeprecated = [1, '1'];
        
            if (escapeKeys.includes(event.key) || escapeKeyCodes.includes(event.keyCode) || escapeKeyCodesDeprecated.includes(event.keyCode)) {
                modal.style.display = 'none';
                resolve();
            }
        };
    });
}

